"""Tables (eval/results/tables.md) and plots (eval/plots/) from run JSON."""

import json
import math
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

T95 = {2: 12.706, 3: 4.303}


def ci(xs):
    mu = float(np.mean(xs))
    h = T95.get(len(xs), 2.0) * float(np.std(xs, ddof=1)) / math.sqrt(len(xs)) \
        if len(xs) > 1 else float("nan")
    return mu, h


runs = [json.loads(p.read_text()) for p in sorted(Path("eval/results/runs").glob("*.json"))]
by = defaultdict(list)
for r in runs:
    by[r["target_eps"]].append(r)
eps_keys = sorted(by, key=lambda e: (math.isinf(e), e))
out = ["# Results (generated by scripts/make_tables.py)\n",
       "FashionMNIST, tanh CNN (26k params), 10 epochs, expected batch 256, δ = 1e-5, "
       "3 seeds (mean ± 95% t-CI).\n",
       "| target ε | σ | test accuracy % | MIA AUC (loss threshold) | MIA TPR @ 0.1% FPR | "
       "canary AUC | audited ε lower bound (95%) |", "|---|---|---|---|---|---|---|"]
for e in eps_keys:
    rs = by[e]
    acc = ci([100 * r["accuracy"] for r in rs])
    mia = ci([r["mia_auc"] for r in rs])
    tpr = ci([100 * r["mia_tpr_at_0.1pct_fpr"] for r in rs])
    can = ci([r["canary_auc"] for r in rs])
    lbs = [r["audit"]["eps_lower"] for r in rs]
    sig = "-" if rs[0]["sigma"] is None else f"{rs[0]['sigma']:.3f}"
    label = "∞ (non-private)" if math.isinf(e) else f"{e:g}"
    out.append(f"| {label} | {sig} | {acc[0]:.1f} ± {acc[1]:.1f} | {mia[0]:.3f} ± {mia[1]:.3f} "
               f"| {tpr[0]:.2f} ± {tpr[1]:.2f}% | {can[0]:.3f} ± {can[1]:.3f} | "
               f"{np.mean(lbs):.2f} (per seed {', '.join(f'{x:.2f}' for x in lbs)}) |")
noise = [json.loads(p.read_text()) for p in sorted(Path("eval/results/runs_noise").glob("*.json"))]
if noise:
    mis = {(r["target_eps"], r["seed"]): r for r in runs}
    out += ["\n## Canary type ablation (seed 0): mislabeled real images vs random-noise images\n",
            "| target ε | canary AUC (mislabeled) | ε lower bound (mislabeled) | canary AUC "
            "(noise) | ε lower bound (noise) | test acc % (noise run) |",
            "|---|---|---|---|---|---|"]
    for r in sorted(noise, key=lambda r: (math.isinf(r["target_eps"]), r["target_eps"])):
        m = mis.get((r["target_eps"], r["seed"]))
        label = "∞" if math.isinf(r["target_eps"]) else f"{r['target_eps']:g}"
        out.append(f"| {label} | {m['canary_auc']:.3f} | {m['audit']['eps_lower']:.2f} | "
                   f"{r['canary_auc']:.3f} | {r['audit']['eps_lower']:.2f} | "
                   f"{100 * r['accuracy']:.1f} |")
tune = [json.loads(p.read_text()) for p in sorted(Path("eval/results/tune").glob("*.json"))]
if tune:
    out += ["\n## Learning-rate selection (3-epoch runs, validation split)\n",
            "| setting | lr | validation accuracy |", "|---|---|---|"]
    for r in sorted(tune, key=lambda r: (math.isinf(r["target_eps"]), r["lr"])):
        name = "non-private" if math.isinf(r["target_eps"]) else f"ε = {r['target_eps']:g}"
        out.append(f"| {name} | {r['lr']} | {100 * r['accuracy']:.1f} |")
wall = sum(r["wall_s"] for r in runs + tune + noise) / 60
out.append(f"\nCompute: {wall:.0f} CPU-process minutes of training (4 threads each).\n")
Path("eval/results/tables.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
fin = [e for e in eps_keys if not math.isinf(e)]
xs = np.array(fin)
acc = np.array([ci([100 * r["accuracy"] for r in by[e]]) for e in fin])
axes[0].errorbar(xs, acc[:, 0], yerr=acc[:, 1], marker="o", capsize=3, color="#4C72B0",
                 label="DP-SGD")
if math.inf in by:
    a_inf = ci([100 * r["accuracy"] for r in by[math.inf]])[0]
    axes[0].axhline(a_inf, ls="--", color="#888", label="non-private")
axes[0].set_xscale("log")
axes[0].set_xlabel("ε (δ = 1e-5)")
axes[0].set_ylabel("test accuracy %")
axes[0].legend(frameon=False, fontsize=8)
lb = np.array([np.mean([r["audit"]["eps_lower"] for r in by[e]]) for e in fin])
axes[1].plot(xs, xs, "--", color="#888", label="theoretical upper bound (ε)")
axes[1].plot(xs, lb, "o-", color="#C44E52", label="audited lower bound")
axes[1].set_xscale("log")
axes[1].set_yscale("symlog", linthresh=0.1)
axes[1].set_xlabel("target ε")
axes[1].set_ylabel("ε")
axes[1].legend(frameon=False, fontsize=8)
for ax in axes:
    ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout()
Path("eval/plots").mkdir(parents=True, exist_ok=True)
fig.savefig("eval/plots/privacy_utility_audit.png", dpi=150)
